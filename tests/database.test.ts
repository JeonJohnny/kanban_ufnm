async function login(user = 1, session = user + 10, role = 'authenticated') {
  await db.exec('reset role')
  await db.query("select set_config('request.jwt.claims',$1,false)", [JSON.stringify({ sub: id(user), session_id: id(session) })])
  await db.exec(`set role ${role}`)
}
async function act(action: string, payload: object = {}) {
  const result = await db.query<{ result: { id: string } }>('select public.board_action($1,$2::jsonb) as result', [action, JSON.stringify(payload)])
  return result.rows[0].result.id
}
async function count(table: string) { return (await db.query<{ n: number }>(`select count(*)::int as n from public.${table}`)).rows[0].n }
// Expected SQL errors need a savepoint so the enclosing isolation transaction remains usable.
async function denied(fn: () => Promise<unknown>, pattern?: RegExp) {
  await db.exec('savepoint denied')
  try { await expect(fn()).rejects.toThrow(pattern) } finally { await db.exec('rollback to savepoint denied') }
}
